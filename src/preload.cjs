const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('lens', {
  displays: () => ipcRenderer.invoke('list-displays'),
  findBoard: () => ipcRenderer.invoke('find-board'),
  reviewRegions: () => ipcRenderer.invoke('region-review-data'),
  confirmRegions: regions => ipcRenderer.invoke('confirm-region-review',regions),
  cancelRegions: () => ipcRenderer.invoke('cancel-region-review'),
  onReviewCancelled: callback => ipcRenderer.on('region-review-cancelled',()=>callback()),
  selectBoard: (id,kind) => ipcRenderer.invoke('select-board',id,kind),
  selectRegion: rect => ipcRenderer.invoke('region-selected', rect),
  paint: data => ipcRenderer.invoke('paint-board', data),
  openCoach: () => ipcRenderer.invoke('open-coach'),
  openStreamView: () => ipcRenderer.invoke('open-stream-view'),
  publishCoach: state => ipcRenderer.send('coach-state',state),
  onCoachState: callback => ipcRenderer.on('coach-state',(_,state)=>callback(state)),
  chooseCoachVariation: (position,id) => ipcRenderer.invoke('choose-coach-variation',position,id),
  onCoachVariation: callback => ipcRenderer.on('coach-variation',(_,choice)=>callback(choice)),
  onCoachOverlap: callback => ipcRenderer.on('coach-overlap',(_,targets)=>callback(targets)),
  askCoach: data => ipcRenderer.invoke('ask-coach',data),
  capture: (calibration = false) => ipcRenderer.invoke('capture-board', calibration === true),
  captureMoveList: (anchor,id,quick=false) => ipcRenderer.invoke('capture-move-list',anchor,id,quick),
  trackingFrame: signature => ipcRenderer.invoke('tracking-frame',signature),
  confirmTrackingFrame: id => ipcRenderer.invoke('confirm-tracking-frame',id),
  diagnosticsEnabled: value => ipcRenderer.invoke('diagnostics-enabled',value),
  diagnosticsSnapshot: () => ipcRenderer.invoke('diagnostics-snapshot'),
  diagnosticsEvent: entry => ipcRenderer.send('diagnostics-event',entry),
  diagnosticsState: state => ipcRenderer.send('diagnostics-state',state),
  diagnosticsClear: () => ipcRenderer.invoke('diagnostics-clear'),
  diagnosticsInspect: fen => ipcRenderer.invoke('diagnostics-inspect',fen),
  diagnosticsExport: () => ipcRenderer.invoke('diagnostics-export'),
  moveListSignature: () => ipcRenderer.invoke('move-list-signature'),
  clearMoveList: () => ipcRenderer.invoke('clear-move-list'),
  onMoveList: callback => ipcRenderer.on('move-list-selected',(_,selected)=>callback(selected)),
  chess: (action, data) => ipcRenderer.invoke('chess', action, data),
  catalog: (action,data) => ipcRenderer.invoke('catalog',action,data),
  coachPosition: (fen,hints,online,onlyOnline=false,usual=null) => ipcRenderer.invoke('coach-position',fen,hints,online,onlyOnline===true,usual),
  onlineMasters: (fen,token) => ipcRenderer.invoke('online-masters',fen,token),
  tokenPage: () => ipcRenderer.invoke('online-token-page'),
  importPgn: () => ipcRenderer.invoke('import-pgn'),
  onBoard: callback => ipcRenderer.on('board-selected', (_, rect) => callback(rect)),
  onDisplays: callback => ipcRenderer.on('displays-changed', () => callback()),
  onPaint: callback => ipcRenderer.on('paint', (_, data) => callback(data))
});
